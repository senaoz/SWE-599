"""Data card for the cleaned BOUN works (research/data/boun/). Writes research/audit/BOUN_DATA.md.

Compares the 2026-10 OpenAlex refetch with the app's `research/data/cleaned/boun.csv`.
Every number in the card is computed here.

    research/.venv/bin/python research/audit/boun_data_report.py
"""
from __future__ import annotations

import gzip
import json
from collections import Counter
from pathlib import Path

import pandas as pd

RESEARCH = Path(__file__).resolve().parents[1]
DATA = RESEARCH / "data" / "boun"
OUT = Path(__file__).resolve().parent / "BOUN_DATA.md"


def table(counter: Counter | dict, head: tuple[str, str]) -> str:
    rows = [f"| {head[0]} | {head[1]} |", "|---|---|"]
    rows += [f"| {k} | {v:,} |" for k, v in counter.items()]
    return "\n".join(rows)


def main() -> None:
    raw = [json.loads(line) for line in gzip.open(DATA / "works_openalex.jsonl.gz", "rt")]
    df = pd.read_csv(DATA / "boun_works.csv.gz")
    for c in ("dq_strong", "dq_weak", "boun_author_ids", "duplicate_ids"):
        df[c] = df[c].map(json.loads)
    rw = pd.read_csv(DATA / "researcher_works.csv.gz")
    people = pd.read_csv(DATA / "researchers.csv.gz", keep_default_na=False)
    stats = json.loads((DATA / "build_stats.json").read_text())
    old = pd.read_csv(RESEARCH / "data" / "cleaned" / "boun.csv", low_memory=False, usecols=["id", "abstract"])

    all_ids = {w["id"] for w in raw}
    clean_ids = set(df["id"]) | {d for ds in df["duplicate_ids"] for d in ds}
    old_ids = set(old["id"])
    types_raw = Counter(w["type"] for w in raw)
    dropped_types = Counter({t: n for t, n in types_raw.items() if t not in set(df["type"])})
    per_researcher = rw.groupby("researcher_id").size()
    collab = set(df.loc[df["large_collaboration"], "id"])
    collab_only = int(rw.assign(c=rw["work_id"].isin(collab)).groupby("researcher_id")["c"].all().sum())
    has_text = df["abstract_source"] != "none"
    strong = df["dq_strong"].str.len() > 0

    lines = [
        "# BOUN works: data card and audit (TODO 6B.1)",
        "",
        "Generated by `research/audit/boun_data_report.py` from `research/data/boun/` "
        "(built by `research/scripts/build_boun_clean.py`; fetch and build steps are logged in `docs/DEVLOG.md`, 2026-10-15).",
        "",
        "## Source",
        "",
        f"- OpenAlex, filter `authorships.institutions.lineage:i4405392, publication_year:2020-`, all work types: "
        f"**{stats['fetched']:,}** records (`works_openalex.jsonl.gz`, raw, CC0).",
        "- List-endpoint records stop at 100 authorships. For every such record the full author list was fetched with a "
        "single-work call and only the BOUN authorships were kept.",
        "- Missing abstracts were looked up by DOI in Crossref and Semantic Scholar (free tiers). Their text is **not** "
        "in the repository (publisher copyright; the repository is public): the table records only `abstract_source`, "
        "and the text stays in the gitignored cache `research/data/v2/boun/`.",
        "- The app still seeds from `research/data/cleaned/boun.csv`, which is unchanged.",
        "",
        "## Cleaning",
        "",
        f"- **Types kept:** research outputs ({stats['research_types']:,} records). Dropped types:",
        "",
        table(dropped_types, ("Dropped type", "Records")),
        "",
        f"- **Duplicates merged:** {stats['merged_duplicates']:,} records into other records (same DOI, or the same "
        "normalized title within one year; `src.cograph.canonical_map`). The canonical record prefers a non-preprint "
        f"with text; `first_date` keeps the earliest date in the group ({int((df['first_date'] < df['publication_date']).sum()):,} "
        f"works have an earlier preprint or version). Result: **{len(df):,} works**.",
        "- **Language:** decided from title and abstract by stopword counts (`src.boun_data.language_flag`); the OpenAlex "
        "`language` tag is not used because it is unreliable (e.g. English ATLAS papers tagged `lv`). "
        f"All {sum(w.get('language') == 'tr' for w in raw):,} OpenAlex-`tr` records were reviewed by hand against the rule.",
        "",
        table(df["language_flag"].value_counts().to_dict(), ("Language flag", "Works")),
        "",
        "## Contents",
        "",
        table(df["type"].value_counts().to_dict(), ("Type", "Works")),
        "",
        f"- **Researchers:** {rw['researcher_id'].nunique():,} BOUN author ids, {len(rw):,} researcher–work rows; "
        f"works per researcher: median {per_researcher.median():.0f}, "
        f"{(per_researcher >= 2).sum():,} researchers with at least 2 works, {(per_researcher >= 5).sum():,} with at least 5. "
        f"Names are in `researchers.csv.gz` ({int((people['display_name'] != '').sum()):,} of {len(people):,} named).",
        f"- **Misattributed collaborations:** {stats['suspect_large_works']:,} large works list more than "
        "20 BOUN authors (OpenAlex attached the BOUN affiliation to the wrong authors; real groups have a median of 6 per "
        "paper). On these works only BOUN authors confirmed by another work are kept (`boun_attribution_suspect`).",
        f"- **Large collaborations** (100+ authors): {int(df['large_collaboration'].sum()):,} works; "
        f"{collab_only:,} researchers have only such works, so their profile is collaboration papers alone.",
        f"- **Works with no attributable BOUN author:** {int((df['boun_author_ids'].str.len() == 0).sum()):,} "
        "(no author id on the BOUN authorship, or no authorships at all).",
        f"- **Retracted:** {int(df['is_retracted'].sum()):,}. **Year-only dates** (`YYYY-01-01`): {int(df['year_only_date'].sum()):,}.",
        f"- **Years:** " + ", ".join(f"{y}: {n:,}" for y, n in df["publication_year"].value_counts().sort_index().items()) + ".",
        "",
        "## Abstracts",
        "",
        table(df["abstract_source"].value_counts().to_dict(), ("Abstract source", "Works")),
        "",
        f"- Text available for **{has_text.sum():,} of {len(df):,}** works ({100 * has_text.mean():.1f}%).",
        f"- Quality flags (heuristics from `research/audit/data_quality.py`, for review): any strong flag "
        f"{int(strong.sum()):,}; " + ", ".join(f"`{f}` {n:,}" for f, n in Counter(x for xs in df['dq_strong'] for x in xs).most_common())
        + "; weak: " + ", ".join(f"`{f}` {n:,}" for f, n in Counter(x for xs in df['dq_weak'] for x in xs).most_common()) + ".",
        "",
        "## Against the app's `boun.csv`",
        "",
        f"- `boun.csv`: {len(old):,} records, {int(old['abstract'].isna().sum()):,} without an abstract "
        f"({100 * old['abstract'].isna().mean():.1f}%).",
        f"- In both: {len(old_ids & clean_ids):,}. Only in `boun.csv`: {len(old_ids - clean_ids):,} "
        f"(of which {len(old_ids - all_ids):,} are no longer returned by the BOUN filter and "
        f"{len((old_ids & all_ids) - clean_ids):,} were dropped here by type). Only in the new data: {len(clean_ids - old_ids):,}.",
        "- `boun.csv` keeps types that are not research outputs (e.g. errata and editorials, now typed as such by OpenAlex), "
        "misses conference papers, preprints and book chapters, and its author lists stop at 100 for large collaborations.",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
