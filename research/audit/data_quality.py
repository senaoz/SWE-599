"""Flag OpenAlex "abstracts" that are probably not abstracts (TODO 1.5).

Reads the v2 eval sets (both benchmarks) and checks every paper they use: queries,
positives and negatives. Flags are heuristics, meant for review rather than automatic
filtering. Writes research/audit/DATA_QUALITY.md.

    research/.venv/bin/python research/audit/data_quality.py
"""
from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

RESEARCH = Path(__file__).resolve().parents[1]
OUT = Path(__file__).resolve().parent / "DATA_QUALITY.md"

# Strong: the text is very likely not an abstract of this paper.
STRONG = {
    "author_list": lambda a: len(re.findall(r"\b(MD|PhD|MPH|MSc|MS|BS|ScD|DPhil)\b", a)) >= 2 and len(a) < 400,
    "citation_string": lambda a: re.match(r"^[A-Z][^.]{0,60} et al\.,? \(\d{4}\)", a) is not None,
    "boilerplate": lambda a: re.search(
        r"competing interests|conflicts? of interest|all rights reserved|this article is protected|"
        r"the publisher is not responsible|©", a, re.I) is not None and len(a) < 600,
    "title_like": lambda a: len(a) < 200 and not re.search(r"[.!?]\s+\S", a.rstrip(".…")) and a.count(" ") < 30,
    "fragment": lambda a: bool(a) and (a[0].islower() or a.startswith("...")),
}
# Weak: worth a look, but common in genuine abstracts.
WEAK = {
    "short_under_300": lambda a: len(a) < 300,
    "availability_or_url": lambda a: re.search(
        r"(freely|publicly) available|available (at|from|online)|source code|github\.com|https?://|www\.|doi\.org",
        a, re.I) is not None,
}
FLAGS = {**STRONG, **WEAK}


def load_papers() -> tuple[dict, dict[str, set[str]], dict[str, str]]:
    papers, roles, splits = {}, {}, {}
    for bench in ("random", "concept"):
        ds = json.loads((RESEARCH / "v2" / "eval_sets" / f"eval_sets_{bench}.json").read_text())
        papers.update(ds["papers"])
        splits.update(ds["splits"])
        for s in ds["sets"]:
            roles.setdefault(s["pi_id"], set()).add("query")
            for c in s["positives"]:
                roles.setdefault(c, set()).add("positive")
            for c in s["negatives"]:
                roles.setdefault(c, set()).add("negative")
    return papers, roles, splits


def sensitivity(strong_queries: set[str]) -> list[str]:
    """Test-split R-precision with and without the strong-flagged query papers."""
    import sys
    sys.path.insert(0, str(RESEARCH))
    from src.pipeline_v2 import load_runs
    from src.stats_v2 import per_query

    tag = "{fields}_{max_chars}_{query_max_chars}".format(**json.loads((RESEARCH / "v2" / "config.json").read_text()))
    out = ["", "## Sensitivity: results without strong-flagged queries", "",
           "Test-split R-precision (%), seed-averaged, with all test queries vs without the strong-flagged ones.", ""]
    for bench in ("random", "concept"):
        pq = per_query(load_runs(bench, tag, split="test"))
        keep = ~pq["pi_id"].isin(strong_queries)
        a, c = pq.groupby("method")["rprec"].mean(), pq[keep].groupby("method")["rprec"].mean()
        n_out = pq.loc[~keep, "pi_id"].nunique()
        out += [f"**{bench}** ({pq['pi_id'].nunique()} → {pq['pi_id'].nunique() - n_out} queries)", "",
                "| Method | All | Without flagged | Δ |", "|---|---|---|---|"]
        out += [f"| {m} | {a[m]:.1f} | {c[m]:.1f} | {c[m] - a[m]:+.1f} |" for m in a.sort_values(ascending=False).index]
        out.append("")
    return out


def main() -> None:
    papers, roles, splits = load_papers()
    flagged = {pid: [f for f, test in FLAGS.items() if test(papers[pid]["abstract"])] for pid in roles}
    flagged = {pid: f for pid, f in flagged.items() if f}
    strong = {pid for pid, fs in flagged.items() if set(fs) & set(STRONG)}
    non_en = {pid for pid in roles if papers[pid]["language"] not in ("en", "")}

    by_flag = Counter(f for fs in flagged.values() for f in fs)
    by_role = Counter(r for pid in flagged for r in roles[pid])
    total_role = Counter(r for rs in roles.values() for r in rs)

    lines = [
        "# Data quality of v2 abstracts (TODO 1.5)",
        "",
        "Generated by `research/audit/data_quality.py`. The flags are heuristics for review; nothing was filtered.",
        "",
        f"Papers checked: {len(roles)} (every query, positive and negative in the `random` and `concept` benchmarks).",
        "",
        "**Summary.**",
        "",
        "- About 6% of papers carry text that is very likely not their abstract. Examples: author lists (\"Michael Klompas, MD, MPH; …\"), citation strings (\"Wu et al., (2020). pyOptSparse …\"), a competing-interests statement, journal standfirsts (\"Build more capacity, and stretch what we already have\"), sentence fragments, and in two COVID queries the *title of another paper*.",
        "- One paper appears as two query records: *Coronavirus disease 2019: the harms of exaggerated information…* is `W3012006042` (dev) and `W4247191450` (test, abstract \"None.\"). This is a near-duplicate across the dev/test split. Its effect is negligible because only the text config and k were tuned on dev.",
        "- Removing the strong-flagged test queries changes no method's R-precision by more than about 1 point and leaves the method ranking unchanged (see the sensitivity section). The data were therefore **not filtered**, and the issue is reported as a limitation. A future benchmark should drop these records or replace them with full-text abstracts.",
        "",
        "| Flag | Papers |",
        "|---|---|",
        *[f"| `{f}` | {by_flag.get(f, 0)} |" for f in FLAGS],
        f"| **any strong flag** | **{len(strong)}** |",
        f"| any flag | {len(flagged)} |",
        f"| non-English (`language` ≠ en) | {len(non_en)} |",
        "",
        "Strong flags (`" + "`, `".join(STRONG) + "`) mark text that is very likely not this paper's abstract. "
        "Weak flags (`" + "`, `".join(WEAK) + "`) are common in genuine short abstracts (e.g. JAMA Viewpoint summaries).",
        "",
        "| Role | Strong-flagged / total | Any flag / total |",
        "|---|---|---|",
        *[f"| {r} | {sum(1 for pid in strong if r in roles[pid])} / {total_role[r]} | {by_role.get(r, 0)} / {total_role[r]} |"
          for r in ("query", "positive", "negative")],
        "",
        "## Queries with a strong flag",
        "",
    ]
    queries = [pid for pid in strong if "query" in roles[pid]]
    if not queries:
        lines.append("None.")
    for pid in sorted(queries):
        p = papers[pid]
        lines.append(f"- `{pid.rsplit('/', 1)[-1]}` ({splits.get(pid, '?')}) *{p['title'][:90]}*: "
                     f"{', '.join(flagged[pid])}. Abstract starts: \"{p['abstract'][:160]}…\"")
    lines += ["", "## Candidates with a strong flag (first 15)", ""]
    cands = [pid for pid in sorted(strong) if "query" not in roles[pid]][:15]
    for pid in cands:
        p = papers[pid]
        lines.append(f"- `{pid.rsplit('/', 1)[-1]}` ({'/'.join(sorted(roles[pid]))}; {', '.join(flagged[pid])}) "
                     f"*{p['title'][:80]}*: \"{p['abstract'][:140]}…\"")
    if non_en:
        lines += ["", "## Non-English papers", ""]
        for pid in sorted(non_en):
            p = papers[pid]
            lines.append(f"- `{pid.rsplit('/', 1)[-1]}` ({'/'.join(sorted(roles[pid]))}, `{p['language']}`) *{p['title'][:90]}*")
    lines += sensitivity({pid for pid in strong if "query" in roles[pid]})
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:22]))


if __name__ == "__main__":
    main()
